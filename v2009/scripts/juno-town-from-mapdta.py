#!/usr/bin/env python3
"""Place the old Juno town NPCs where a classic client's map shows them.

    v2009/scripts/juno-town-from-mapdta.py <classic Data/Map.dta> > v2009/server-config/zone0-town-mapdta.sql

The in-game map (Data/Map.dta, read by CUIMap::ReadMapData, 2009 UIMap.cpp) lists, per zone, the NPCs
it marks with their (x, z). The BR2014 file has the new Juno; the "Last Chaos Brasil Clássico"
client's file has the old Juno (startzone.wld), which is what the 2009 client draws.
Each listed NPC's zone 0 rows in lc2009_data.t_npc_regen (or its t_shop row) get that position;
the direction is kept. An NPC listed once with several regen rows (Mysterious Statue) gets its listed
spots in order and the remaining rows are disabled. Indices with no NPC proto and NPCs whose listed
spot is still the new Juno's (outside the old map's town) are skipped and reported on stderr.
"""
import pathlib
import struct
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SAT = ROOT / "run/GameServer/data/StartZone_1536_1536_0.sat"
W = 1536
SKIP = {893}  # Elizabeth: the classic file still has her new-Juno spot (578.8, 866), on a hillside


def parse(path):
    b = pathlib.Path(path).read_bytes()
    o = 0

    def r(fmt):
        nonlocal o
        v = struct.unpack_from("<" + fmt, b, o)
        o += struct.calcsize("<" + fmt)
        return v

    zones = {}
    (n,) = r("i")
    for _ in range(n):
        idx, layer, *_ = r("ibiiiifii")
        (dc,) = r("b")
        for _ in range(dc):
            r("iiiiiiiifff")
        (sc,) = r("b")
        for _ in range(sc):
            r("iffb")
        (nc,) = r("i")
        zones.setdefault(idx, []).extend(r("iiff") for _ in range(nc))
    assert o == len(b), "Map.dta not fully read"
    return zones


def sql(q):
    out = subprocess.run(["mysql", "-N", "-B", "lc2009_data", "-e", q], check=True,
                         capture_output=True, text=True).stdout
    return [line.split("\t") for line in out.splitlines()]


def main():
    spots = {}
    for idx, ylayer, x, z in parse(sys.argv[1])[0]:
        spots.setdefault(idx, []).append((ylayer, x, z))
    sat = SAT.read_bytes()
    protos = {int(i) for (i,) in sql("SELECT a_index FROM t_npc")}
    shops = {int(k) for (k,) in sql("SELECT a_keeper_idx FROM t_shop WHERE a_zone_num=0")}
    print("-- Generated by v2009/scripts/juno-town-from-mapdta.py from the classic client's Data/Map.dta.")
    print("-- Old Juno town NPC positions (zone 0). Idempotent.")
    for idx in sorted(spots):
        if idx not in protos or idx in SKIP:
            print(f"skip NPC {idx}: {'no proto' if idx not in protos else 'listed at its new-Juno spot'}",
                  file=sys.stderr)
            continue
        rows = sql(f"SELECT a_index FROM t_npc_regen WHERE a_zone_num=0 AND a_npc_idx={idx} ORDER BY a_index")
        for n, (ylayer, x, z) in enumerate(spots[idx]):
            attr = sat[int(z) * W + int(x)] if ylayer == 0 else None
            note = f" -- cell attr {attr}" if attr is not None else ""
            if attr == 255:
                print(f"NPC {idx} at ({x:.1f}, {z:.1f}) is on a blocked cell", file=sys.stderr)
            if idx in shops and n == 0:
                print(f"UPDATE t_shop SET a_pos_x={x:.2f}, a_pos_z={z:.2f}, a_y_layer={ylayer} "
                      f"WHERE a_zone_num=0 AND a_keeper_idx={idx};{note}")
            if n < len(rows):
                print(f"UPDATE t_npc_regen SET a_pos_x={x:.2f}, a_pos_z={z:.2f}, a_y_layer={ylayer}, "
                      f"a_total_num=-1 WHERE a_index={rows[n][0]};{note}")
        for (row,) in rows[len(spots[idx]):]:
            print(f"UPDATE t_npc_regen SET a_total_num=0 WHERE a_index={row}; -- NPC {idx}: not on the map")
        if not rows and idx not in shops:
            print(f"NPC {idx} has no zone 0 row", file=sys.stderr)


if __name__ == "__main__":
    main()
