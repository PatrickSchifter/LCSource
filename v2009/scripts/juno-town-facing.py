#!/usr/bin/env python3
"""Turn the old Juno town NPCs to face the open street instead of their new-Juno headings.

    v2009/scripts/juno-town-facing.py > v2009/server-config/zone0-town-facing.sql

For each zone 0 NPC placed from the classic Map.dta (zone0-town-mapdta.sql) and each zone 0 shop,
casts rays every 5 degrees on the installed .sat (1 m cells, 255 = blocked), smooths the free
distance over +-20 degrees and faces the most open direction: NPCs stand with their backs to a
building, facing the street.
Heading convention (a_pos_r, degrees): a player with heading h looks along (-sin h, -cos h) in
(x, z) (Serious Engine: 0 looks to -z, 90 to -x; matches the Animal Trainer's /whereami), , the same
for NPCs (the Animal Trainer looks right with the user's /whereami heading as is), so an NPC
looking along (cos a, sin a) gets r = atan2(-cos a, -sin a).
Rows set by hand in zone0-town-manual.sql are applied after this file and win.
"""
import math
import pathlib
import re
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
SAT = (ROOT / "run/GameServer/data/StartZone_1536_1536_0.sat").read_bytes()
W = 1536


def blocked(x, z):
    xi, zi = int(x), int(z)
    return not (0 <= xi < W and 0 <= zi < W) or SAT[zi * W + xi] == 255


def free(x, z, a, maxd=40.0):
    dx, dz = math.cos(a), math.sin(a)
    d = 0.0
    while d < maxd:
        d += 0.5
        if blocked(x + dx * d, z + dz * d):
            return d
    return maxd


def heading(x, z):
    raw = [free(x, z, math.radians(a)) for a in range(0, 360, 5)]
    n = len(raw)
    sm = [sum(raw[(i + k) % n] for k in range(-4, 5)) for i in range(n)]
    a = math.radians(5 * max(range(n), key=lambda i: sm[i]))
    return round(math.degrees(math.atan2(-math.cos(a), -math.sin(a))), 1)


def sql(q):
    out = subprocess.run(["mysql", "-N", "-B", "lc2009_data", "-e", q], check=True,
                         capture_output=True, text=True).stdout
    return [line.split("\t") for line in out.splitlines()]


def main():
    placed = (ROOT / "server-config/zone0-town-mapdta.sql").read_text()
    regen = sorted({int(i) for i in re.findall(r"t_npc_regen SET a_pos_x=.*WHERE a_index=(\d+)", placed)})
    print("-- Generated by v2009/scripts/juno-town-facing.py: old Juno town NPCs face the open street.")
    for idx in regen:
        ((x, z, npc),) = sql(f"SELECT a_pos_x, a_pos_z, a_npc_idx FROM t_npc_regen WHERE a_index={idx}")
        print(f"UPDATE t_npc_regen SET a_pos_r={heading(float(x), float(z))} WHERE a_index={idx}; -- NPC {npc}")
    for keeper, x, z in sql("SELECT a_keeper_idx, a_pos_x, a_pos_z FROM t_shop WHERE a_zone_num=0"):
        print(f"UPDATE t_shop SET a_pos_r={heading(float(x), float(z))} "
              f"WHERE a_zone_num=0 AND a_keeper_idx={keeper};")


if __name__ == "__main__":
    main()
