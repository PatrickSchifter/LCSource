#!/usr/bin/env python3
"""Put the zone 0 (old Juno) gathering nodes inside their production circles.

    v2009/scripts/juno-gathering.py > v2009/server-config/zone0-gathering.sql

The user stood in each gathering area in game and ran /whereami. Each spot lies in a production
area of the zone 0 .sat (attr 20/30); the area is flood-filled from that cell and the nodes are
spread inside it (fixed seed, minimum spacing, cells around a node also production).
"""
import math
import pathlib
import random
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent
SAT = (ROOT / "run/GameServer/data/StartZone_1536_1536_0.sat").read_bytes()
W = 1536
PROD = (20, 30)

# (/whereami spot, NPC protos, which rows: "near" = rows whose current spot is closest to this area)
AREAS = [
    ("energy crystals 1", (910.66, 1008.79), (107, 108)),
    ("energy crystals 2", (1218.94, 700.21), (107, 108)),
    ("bromelias (herbs)", (1147.43, 707.94), (105, 106)),
    ("mines", (1322.12, 694.64), (103, 104)),
]


def area(x, z):
    start = int(z) * W + int(x)
    assert SAT[start] in PROD, (x, z, SAT[start])
    seen, stack = {start}, [start]
    while stack:
        i = stack.pop()
        cx, cz = i % W, i // W
        for nx, nz in ((cx + 1, cz), (cx - 1, cz), (cx, cz + 1), (cx, cz - 1)):
            j = nz * W + nx
            if 0 <= nx < W and 0 <= nz < W and j not in seen and SAT[j] in PROD:
                seen.add(j)
                stack.append(j)
    return seen


def rows(protos):
    q = ("SELECT a_index, a_npc_idx, a_pos_x, a_pos_z FROM t_npc_regen WHERE a_zone_num=0 "
         f"AND a_total_num<>0 AND a_npc_idx IN ({','.join(map(str, protos))}) ORDER BY a_index")
    out = subprocess.run(["mysql", "-N", "-B", "lc2009_data", "-e", q], check=True,
                         capture_output=True, text=True).stdout
    return [(int(a), int(b), float(c), float(d)) for a, b, c, d in (l.split("\t") for l in out.splitlines())]


def main():
    print("-- Generated by v2009/scripts/juno-gathering.py: zone 0 gathering nodes in their production")
    print("-- areas (spots set in game with /whereami). Applied after zone0-mobs-map.sql. Idempotent.")
    by_proto = {}
    for name, spot, protos in AREAS:
        by_proto.setdefault(protos, []).append((name, spot))
    rnd = random.Random(2009)
    for protos, areas in by_proto.items():
        nodes = rows(protos)
        # split the rows between the areas of the same kind by the nearest spot (original clusters)
        groups = {name: [] for name, _ in areas}
        for n in nodes:
            name = min(areas, key=lambda a: (a[1][0] - n[2]) ** 2 + (a[1][1] - n[3]) ** 2)[0]
            groups[name].append(n)
        if len(areas) > 1 and min(len(g) for g in groups.values()) == 0:  # keep every area stocked
            nodes.sort(key=lambda n: n[0])
            groups = {name: nodes[i::len(areas)] for i, (name, _) in enumerate(areas)}
        for name, spot in areas:
            cells = area(*spot)
            inner = [c for c in cells if all(((c // W) + dz) * W + (c % W) + dx in cells
                                              for dx in (-1, 0, 1) for dz in (-1, 0, 1))]
            spacing = max(2.5, min(4.5, math.sqrt(len(inner) / max(1, len(groups[name]))) * 0.8))
            pts = []
            tries = 0
            while len(pts) < len(groups[name]):
                c = rnd.choice(inner)
                x, z = c % W + 0.5, c // W + 0.5
                tries += 1
                if tries > 20000 or all((x - px) ** 2 + (z - pz) ** 2 >= spacing ** 2 for px, pz in pts):
                    pts.append((x, z))
            print(f"-- {name}: {len(groups[name])} nodes in {len(cells)} cells around {spot}")
            for (idx, npc, _, _), (x, z) in zip(groups[name], pts):
                print(f"UPDATE t_npc_regen SET a_pos_x={x:.1f}, a_pos_z={z:.1f}, a_y_layer=0 WHERE a_index={idx}; -- {npc}")


if __name__ == "__main__":
    main()
