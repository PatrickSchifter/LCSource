#!/usr/bin/env python3
"""Generate CMake source lists for the client from the original VS2010 projects.

    scripts/vcxproj-to-cmake.py [CONFIG]      (default CONFIG: BRZLIVE)

For Engine, EntitiesMP, GameMP, Shaders and Nksp it writes
"Client Source/cmake/<Project>_sources.cmake" with:
  <PROJECT>_SOURCES      files compiled in CONFIG|Win32 (paths relative to "Client Source")
  <PROJECT>_PCH_CREATE   the file that creates the precompiled header
  <PROJECT>_NO_PCH       files compiled without the precompiled header
  <PROJECT>_ES           .es files that the Entity Class Compiler turns into C++
"""
import pathlib
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent / "Client Source"
NS = {"m": "http://schemas.microsoft.com/developer/msbuild/2003"}
PROJECTS = {
    "Engine": "Engine/Engine_2010.vcxproj",
    "EntitiesMP": "EntitiesMP/EntitiesMP_2010.vcxproj",
    "GameMP": "GameMP/GameMP_2010.vcxproj",
    "Shaders": "Shaders/Shaders_2010.vcxproj",
    "Nksp": "Nksp/Nksp_2010.vcxproj",
}


def applies(element, config):
    cond = element.get("Condition")
    return cond is None or f"{config}|Win32" in cond


def flag(item, tag, config, value):
    return any(applies(x, config) and (x.text or "").strip().lower() == value
               for x in item.iterfind(f"m:{tag}", NS))


def rel(project_dir, include):
    path = (project_dir / include.replace("\\", "/")).resolve()
    # The checkout may differ in case from the project file (case-insensitive Windows paths).
    if not path.exists():
        parent = path.parent
        if parent.exists():
            matches = [p for p in parent.iterdir() if p.name.lower() == path.name.lower()]
            if matches:
                path = matches[0]
    return path.relative_to(ROOT).as_posix()


def main():
    config = sys.argv[1] if len(sys.argv) > 1 else "BRZLIVE"
    out_dir = ROOT / "cmake"
    out_dir.mkdir(exist_ok=True)
    for name, proj in PROJECTS.items():
        project_dir = (ROOT / proj).parent
        root = ET.parse(ROOT / proj).getroot()
        sources, pch_create, no_pch, es = [], [], [], []
        for item in root.iterfind(".//m:ClCompile", NS):
            inc = item.get("Include")
            if not inc or flag(item, "ExcludedFromBuild", config, "true"):
                continue
            path = rel(project_dir, inc)
            # Files removed by the port (Windows-only or dead code) stay listed in the old projects.
            if not (ROOT / path).exists():
                continue
            sources.append(path)
            if flag(item, "PrecompiledHeader", config, "create"):
                pch_create.append(path)
            if flag(item, "PrecompiledHeader", config, "notusing"):
                no_pch.append(path)
        for item in root.iterfind(".//m:CustomBuild", NS):
            inc = item.get("Include")
            if inc and inc.lower().endswith(".es") and not flag(item, "ExcludedFromBuild", config, "true"):
                es.append(rel(project_dir, inc))
        # Ecc output is generated, not checked in: compile it from the build tree instead.
        generated = {e[:-3] + ".cpp" for e in es}
        sources = [s for s in sources if s not in generated]
        upper = name.upper()
        lines = [f"# Generated by scripts/vcxproj-to-cmake.py from {proj} ({config}|Win32). Do not edit.", ""]
        for var, files in ((f"{upper}_SOURCES", sources), (f"{upper}_PCH_CREATE", pch_create),
                           (f"{upper}_NO_PCH", no_pch), (f"{upper}_ES", es)):
            lines.append(f"set({var}")
            lines += [f'  "{f}"' for f in sorted(files)]
            lines.append(")")
            lines.append("")
        (out_dir / f"{name}_sources.cmake").write_text("\n".join(lines))
        print(f"{name}: {len(sources)} sources, {len(es)} .es, pch={pch_create}, no_pch={len(no_pch)}")


if __name__ == "__main__":
    main()
